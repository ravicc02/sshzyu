- 先为页眉与页脚保留空间，再安排标题、正文、结论。对照两侧保持相当宽度与文字密度，留足内边距和行距。内容过多时缩短说明或减少模块，不挤压品牌区、不缩小正文硬塞，不为突出标题吞掉整行正文空间。
