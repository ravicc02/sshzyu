- 为内容指定必要的图标、线性插画、抽象图形或节点，说明位置、大小和语义。图标统一线宽与尺寸，避免每句话都加圆形图标。箭头只表达明确的方向或因果关系，同一含义用一条带标签的箭头，不使用多根无区别的大箭头占据中央留白。
