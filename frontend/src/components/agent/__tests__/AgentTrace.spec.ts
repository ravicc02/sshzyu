import { mount } from '@vue/test-utils'
import { afterEach, describe, expect, it, vi } from 'vitest'
import AgentTrace from '../AgentTrace.vue'
import type { AgentTraceStep } from '@/api/agent'
const thought: AgentTraceStep = { id: 'model-0', kind: 'reasoning', name: 'gpt-6.1-sol', status: 'completed', started_at: '2026-10-19T00:00:00Z', ended_at: '2026-10-19T00:00:05Z', summary: '**需求已整理**，将使用生图工具。', cost_usd: '0.01' }
const tool: AgentTraceStep = { id: 'tool-0', kind: 'tool', name: 'generate_image', status: 'running', started_at: '2026-10-19T00:00:05Z', arguments: { prompt: '蓝色纸船，白色背景', model: 'gpt-image-2.5-sunburst', image_size: '1K', aspect_ratio: '1:1', reference_count: 1 } }
afterEach(() => vi.useRealTimers())
describe('Agent process trace', () => {
  it('folds completed summaries and exposes accessible expansion controls', async () => {
    const w = mount(AgentTrace, { props: { steps: [thought] } })
    const button = w.get('button')
    expect(button.attributes('aria-expanded')).toBe('false')
    expect(w.find('.reasoning-summary').exists()).toBe(false)
    await button.trigger('click')
    expect(button.attributes('aria-expanded')).toBe('true')
    expect(w.get('.step-content').attributes('id')).toBe(button.attributes('aria-controls'))
    expect(w.get('.reasoning-summary strong').text()).toBe('需求已整理')
    expect(w.text()).toContain('公开摘要')
    expect(w.text()).toContain('5 秒')
    w.unmount()
  })
  it('shows the actual tool name, verified inputs and results', async () => {
    const w = mount(AgentTrace, { props: { steps: [tool] } })
    expect(w.get('button').attributes('aria-expanded')).toBe('true')
    expect(w.text()).toContain('generate_image')
    expect(w.get('.tool-prompt').text()).toBe(tool.arguments!.prompt)
    expect(w.text()).toContain('1K · 1:1')
    expect(w.text()).toContain('1 张')
    await w.setProps({ steps: [{ ...tool, status: 'completed', ended_at: '2026-10-19T00:00:15Z', asset_ids: ['asset-1'], cost_usd: '0.17' }] })
    await w.get('button').trigger('click')
    expect(w.get('.tool-output').text()).toContain('已生成 1 张图片')
    expect(w.text()).toContain('$0.17')
    w.unmount()
  })
  it('respects a manual fold choice when the tool later finishes', async () => {
    const w = mount(AgentTrace, { props: { steps: [tool] } })
    await w.get('button').trigger('click')
    await w.get('button').trigger('click')
    await w.setProps({ steps: [{ ...tool, status: 'completed' }] })
    expect(w.get('button').attributes('aria-expanded')).toBe('true')
    w.unmount()
  })
  it('does not invent reasoning when the upstream supplies no summary', async () => {
    const w = mount(AgentTrace, { props: { steps: [{ ...thought, summary: undefined }] } })
    await w.get('button').trigger('click')
    expect(w.text()).toContain('未返回可展示的思考摘要')
    expect(w.find('.reasoning-summary').exists()).toBe(false)
    w.unmount()
  })
  it.each(['queued', 'running', 'reconciling', 'completed', 'failed', 'cancelled', 'expired'])('renders %s tool state without losing its inputs', async status => {
    const w = mount(AgentTrace, { props: { steps: [{ ...tool, status, error_code: status === 'failed' ? 'AGENT_RECONCILIATION_TIMEOUT' : undefined }] } })
    if (w.get('button').attributes('aria-expanded') === 'false') await w.get('button').trigger('click')
    expect(w.get('.tool-prompt').text()).toBe(tool.arguments!.prompt)
    expect(w.get('.step-state').text()).not.toBe('处理中')
    if (status === 'reconciling') expect(w.text()).toContain('不会自动重新调用')
    if (status === 'failed') expect(w.text()).toContain('费用以最终账单为准')
    w.unmount()
  })
  it('updates a live duration but freezes it at the confirmed end time', async () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-10-19T00:00:05Z'))
    const w = mount(AgentTrace, { props: { steps: [{ ...thought, status: 'running', ended_at: undefined, summary: undefined }] } })
    expect(w.get('time').text()).toBe('5 秒')
    await vi.advanceTimersByTimeAsync(10000)
    expect(w.get('time').text()).toBe('15 秒')
    await w.setProps({ steps: [{ ...thought, ended_at: '2026-10-19T00:00:17Z' }] })
    await vi.advanceTimersByTimeAsync(60000)
    expect(w.get('time').text()).toBe('17 秒')
    w.unmount()
  })
  it('escapes tool inputs and sanitizes summary HTML and remote media', async () => {
    const w = mount(AgentTrace, { props: { steps: [{ ...thought, summary: '<script>alert(1)</script><img src="https://tracker.test/p"><strong>摘要</strong>' }, { ...tool, arguments: { ...tool.arguments!, prompt: '<img src=x onerror=alert(1)>' } }] } })
    await w.findAll('button')[0]!.trigger('click')
    expect(w.find('script').exists()).toBe(false)
    expect(w.find('img').exists()).toBe(false)
    expect(w.get('.tool-prompt').text()).toContain('<img')
    expect(w.get('.reasoning-summary strong').text()).toBe('摘要')
    w.unmount()
  })
})
