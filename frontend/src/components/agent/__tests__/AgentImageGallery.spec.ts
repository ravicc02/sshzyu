import { mount } from '@vue/test-utils'
import { describe, expect, it } from 'vitest'
import AgentImageGallery from '../AgentImageGallery.vue'
import type { AgentAttachmentView } from '@/utils/agentAttachments'
const assets: AgentAttachmentView[] = ['a', 'b', 'c', 'd'].map(id => ({ id, url: `blob:${id}`, mime_type: 'image/png' }))
describe('Generated image gallery', () => {
  it('shows a horizontal stack and navigates without wrapping or opening preview', async () => {
    const w = mount(AgentImageGallery, { props: { assets } })
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:a')
    expect(w.get('[aria-label="上一张图片"]').attributes('disabled')).toBeDefined()
    await w.get('[aria-label="下一张图片"]').trigger('click')
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:b')
    expect(w.findAll('.gallery-card')).toHaveLength(3)
    expect(w.get('.gallery-card.previous').attributes('inert')).toBeDefined()
    expect(w.emitted('preview')).toBeUndefined()
    await w.get('[aria-label="查看第 4 张图片"]').trigger('click')
    expect(w.get('[aria-label="下一张图片"]').attributes('disabled')).toBeDefined()
    await w.get('.gallery-card.current button').trigger('click')
    expect(w.emitted('preview')).toEqual([['d']]); w.unmount()
  })
  it('preserves selection by ID while outputs stream in, reorder, or reload', async () => {
    const w = mount(AgentImageGallery, { props: { assets: assets.slice(0, 2) } })
    await w.get('[aria-label="下一张图片"]').trigger('click')
    await w.setProps({ assets })
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:b')
    await w.setProps({ assets: [assets[2]!, { ...assets[1]!, url: 'blob:b-reloaded' }, assets[0]!] })
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:b-reloaded')
    await w.setProps({ assets: [assets[0]!] })
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:a'); w.unmount()
  })
  it('supports keyboard and horizontal swipe without stealing vertical scrolling', async () => {
    const w = mount(AgentImageGallery, { props: { assets } })
    await w.trigger('keydown', { key: 'ArrowRight' })
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:b')
    await w.get('.gallery-stage').trigger('touchstart', { touches: [{ clientX: 200, clientY: 80 }] })
    await w.get('.gallery-stage').trigger('touchend', { changedTouches: [{ clientX: 80, clientY: 85 }] })
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:c')
    await w.get('.gallery-stage').trigger('touchstart', { touches: [{ clientX: 200, clientY: 80 }] })
    await w.get('.gallery-stage').trigger('touchend', { changedTouches: [{ clientX: 180, clientY: 200 }] })
    expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:c')
    await w.trigger('keydown', { key: 'Home' }); expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:a')
    await w.trigger('keydown', { key: 'End' }); expect(w.get('.gallery-card.current img').attributes('src')).toBe('blob:d'); w.unmount()
  })
  it('handles loading, decode failures and expired images without a stale preview', async () => {
    const w = mount(AgentImageGallery, { props: { assets: [{ id: 'pending' }, { id: 'bad', failed: true }, { ...assets[0]!, status: 'expired', content_available: false }] } })
    expect(w.get('.gallery-card.current').text()).toContain('正在加载图片')
    await w.get('[aria-label="下一张图片"]').trigger('click')
    await w.get('.gallery-card.current button').trigger('click')
    expect(w.emitted('retry')).toEqual([['bad']])
    await w.get('[aria-label="下一张图片"]').trigger('click')
    expect(w.get('.gallery-card.current').text()).toContain('图片已过期')
    expect(w.find('.gallery-card.current img').exists()).toBe(false)
    expect(w.find('.gallery-card.current button').exists()).toBe(false)
    await w.setProps({ assets })
    await w.get('.gallery-card.current img').trigger('error')
    expect(w.emitted('imageError')).toEqual([['a']]); w.unmount()
  })
})
